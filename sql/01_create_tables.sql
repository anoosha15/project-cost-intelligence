-- Project Cost & Budget Intelligence: schema and tables (synthetic data only)
CREATE SCHEMA COST_DATA;

CREATE COLUMN TABLE COST_DATA.DIM_COST_CENTER (
  COST_CENTER_ID   NVARCHAR(10) PRIMARY KEY,
  COST_CENTER_NAME NVARCHAR(60)
);

CREATE COLUMN TABLE COST_DATA.DIM_VENDOR (
  VENDOR_ID   NVARCHAR(10) PRIMARY KEY,
  VENDOR_NAME NVARCHAR(60)
);

CREATE COLUMN TABLE COST_DATA.DIM_PROJECT (
  PROJECT_ID     NVARCHAR(10) PRIMARY KEY,
  PROJECT_NAME   NVARCHAR(60),
  COST_CENTER_ID NVARCHAR(10),
  PROJECT_TYPE   NVARCHAR(10),
  START_DATE     DATE
);

CREATE COLUMN TABLE COST_DATA.FACT_COST (
  PROJECT_ID NVARCHAR(10),
  PERIOD     DATE,
  ACTUAL     DECIMAL(15,2),
  BUDGET     DECIMAL(15,2),
  CURRENCY   NVARCHAR(3)
);

CREATE COLUMN TABLE COST_DATA.FACT_CAPEX_STATUS (
  PROJECT_ID      NVARCHAR(10),
  APPROVED_BUDGET DECIMAL(15,2),
  SPENT_TO_DATE   DECIMAL(15,2),
  COMMITTED       DECIMAL(15,2),
  PROGRESS_PCT    INTEGER,
  STATUS          NVARCHAR(20),
  CURRENCY        NVARCHAR(3)
);

CREATE COLUMN TABLE COST_DATA.FACT_PR_PO (
  PR_NUMBER    NVARCHAR(12),
  PO_NUMBER    NVARCHAR(12),
  PROJECT_ID   NVARCHAR(10),
  VENDOR_ID    NVARCHAR(10),
  CREATED_DATE DATE,
  PR_AMOUNT    DECIMAL(15,2),
  PO_AMOUNT    DECIMAL(15,2),
  STATUS       NVARCHAR(20),
  CURRENCY     NVARCHAR(3)
);
