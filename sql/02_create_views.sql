-- Reporting views. Fiscal year starts in April (FY2026 = Apr 2025 - Mar 2026).
CREATE VIEW COST_DATA.V_COST_VARIANCE AS
SELECT
  c.PROJECT_ID,
  p.PROJECT_NAME,
  p.PROJECT_TYPE,
  p.COST_CENTER_ID,
  cc.COST_CENTER_NAME,
  c.PERIOD,
  YEAR(c.PERIOD)  AS CAL_YEAR,
  MONTH(c.PERIOD) AS CAL_MONTH,
  CASE WHEN MONTH(c.PERIOD) >= 4 THEN YEAR(c.PERIOD) + 1
       ELSE YEAR(c.PERIOD) END AS FISCAL_YEAR,
  CASE WHEN MONTH(c.PERIOD) >= 4 THEN MONTH(c.PERIOD) - 3
       ELSE MONTH(c.PERIOD) + 9 END AS FISCAL_PERIOD,
  c.ACTUAL,
  c.BUDGET,
  c.ACTUAL - c.BUDGET AS VARIANCE,
  CASE WHEN c.BUDGET = 0 THEN NULL
       ELSE ROUND((c.ACTUAL - c.BUDGET) / c.BUDGET * 100, 2) END AS VARIANCE_PCT,
  c.CURRENCY
FROM COST_DATA.FACT_COST c
JOIN COST_DATA.DIM_PROJECT p      ON p.PROJECT_ID = c.PROJECT_ID
JOIN COST_DATA.DIM_COST_CENTER cc ON cc.COST_CENTER_ID = p.COST_CENTER_ID;

CREATE VIEW COST_DATA.V_CAPEX_STATUS AS
SELECT
  k.PROJECT_ID,
  p.PROJECT_NAME,
  p.COST_CENTER_ID,
  cc.COST_CENTER_NAME,
  k.APPROVED_BUDGET,
  k.SPENT_TO_DATE,
  k.COMMITTED,
  k.APPROVED_BUDGET - k.SPENT_TO_DATE - k.COMMITTED AS REMAINING_BUDGET,
  ROUND(k.SPENT_TO_DATE / k.APPROVED_BUDGET * 100, 1) AS SPENT_PCT,
  k.PROGRESS_PCT,
  k.STATUS,
  k.CURRENCY
FROM COST_DATA.FACT_CAPEX_STATUS k
JOIN COST_DATA.DIM_PROJECT p      ON p.PROJECT_ID = k.PROJECT_ID
JOIN COST_DATA.DIM_COST_CENTER cc ON cc.COST_CENTER_ID = p.COST_CENTER_ID;

CREATE VIEW COST_DATA.V_PR_PO_TRACKING AS
SELECT
  r.PR_NUMBER,
  r.PO_NUMBER,
  r.PROJECT_ID,
  p.PROJECT_NAME,
  r.VENDOR_ID,
  v.VENDOR_NAME,
  r.CREATED_DATE,
  r.PR_AMOUNT,
  r.PO_AMOUNT,
  r.PO_AMOUNT - r.PR_AMOUNT AS PO_VS_PR_DIFF,
  r.STATUS,
  CASE WHEN r.STATUS = 'Invoiced' THEN 'Closed' ELSE 'Open' END AS OPEN_CLOSED,
  r.CURRENCY
FROM COST_DATA.FACT_PR_PO r
JOIN COST_DATA.DIM_PROJECT p ON p.PROJECT_ID = r.PROJECT_ID
JOIN COST_DATA.DIM_VENDOR v  ON v.VENDOR_ID = r.VENDOR_ID;
